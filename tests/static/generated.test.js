/**
 * S4 脚本生成页约定：健康/妈 生成器纪律、EXCLUDE_FILES 双处一致、孤儿工单、
 * 生活点滴 画廊完整性与占位符残留。
 * 对应 AGENTS.md §8。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { ROOT, listFiles, readText, stripComments, extractAttrs, relToRoot, resolveLocal } = require('../helpers');
const { isExempt } = require('../config');

const MA_DIR = path.join(ROOT, '健康', '妈');
const LIFE_DIR = path.join(ROOT, '生活点滴');

test('S4.1 健康/妈/index.html 保持脚本生成标志（禁止手改）', () => {
  const p = path.join(MA_DIR, 'index.html');
  assert.equal(fs.existsSync(p), true, '健康/妈/index.html 缺失');
  assert.match(
    readText(p),
    /GENERATED BY generate_index\.py - DO NOT EDIT/,
    '生成标志注释缺失：页面可能被手改或未按流程生成'
  );
});

test('S4.2 generate_index.py 与 check_consistency.py 的 EXCLUDE_FILES 完全一致（§8.1）', () => {
  const parse = (file) => {
    const src = readText(file);
    const m = /EXCLUDE_FILES\s*=\s*\{([\s\S]*?)\}/.exec(src);
    assert.ok(m, `${relToRoot(file)} 中未找到 EXCLUDE_FILES 定义`);
    return new Set([...m[1].matchAll(/["']([^"']+)["']/g)].map((x) => x[1]));
  };
  const gen = parse(path.join(MA_DIR, 'generate_index.py'));
  const chk = parse(path.join(MA_DIR, 'check_consistency.py'));
  const onlyGen = [...gen].filter((x) => !chk.has(x));
  const onlyChk = [...chk].filter((x) => !gen.has(x));
  assert.deepEqual(
    { onlyGen, onlyChk },
    { onlyGen: [], onlyChk: [] },
    '两处 EXCLUDE_FILES 不一致（新增排除文件必须同步两处）'
  );
});

test('S4.3 孤儿图工单 orphans.json（若存在）必须为空（count=0）', () => {
  const p = path.join(MA_DIR, 'orphans.json');
  if (!fs.existsSync(p)) return; // 本地状态文件，可不存在
  const data = JSON.parse(fs.readFileSync(p, 'utf8'));
  assert.equal(data.count, 0, `有 ${data.count} 张图片待生成解读报告（见 orphans.json）`);
  assert.equal((data.orphans || []).length, 0, 'orphans 数组非空，与 count 不符');
});

test('S4.4 生活点滴：生成页无 {{ 占位符残留（剥注释后）', () => {
  const bad = listFiles('.html', LIFE_DIR).filter((f) => /\{\{/.test(stripComments(readText(f))));
  assert.deepEqual(bad.map(relToRoot), [], '占位符残留页面');
});

test('S4.5 生活点滴画廊双向完整：磁盘记录目录 ⊆ 画廊链接 且 画廊链接均存在', () => {
  const gallery = path.join(LIFE_DIR, 'index.html');
  assert.equal(fs.existsSync(gallery), true, '生活点滴/index.html 缺失');

  const linked = new Set();
  for (const { url } of extractAttrs(stripComments(readText(gallery)))) {
    const m = /^(\d{4}\/[^"'#?]+\/)index\.html$/.exec(url);
    if (m) linked.add(m[1].replace(/\/$/, ''));
  }

  const onDisk = [];
  for (const year of fs.readdirSync(LIFE_DIR, { withFileTypes: true })) {
    if (!year.isDirectory() || !/^\d{4}$/.test(year.name)) continue;
    for (const rec of fs.readdirSync(path.join(LIFE_DIR, year.name), { withFileTypes: true })) {
      if (!rec.isDirectory()) continue;
      if (fs.existsSync(path.join(LIFE_DIR, year.name, rec.name, 'index.html'))) {
        onDisk.push(`${year.name}/${rec.name}`);
      }
    }
  }

  const missingInGallery = onDisk.filter((d) => !linked.has(d) && !isExempt(gallery, 'S4.5', d));
  const deadInGallery = [...linked].filter(
    (d) => !onDisk.includes(d) && !isExempt(gallery, 'S4.5', d)
  );

  assert.deepEqual(
    { missingInGallery, deadInGallery },
    { missingInGallery: [], deadInGallery: [] },
    '画廊与磁盘记录目录不同步：missing=需重跑 gen_life_record.py gallery；dead=画廊存在死链'
  );
});
